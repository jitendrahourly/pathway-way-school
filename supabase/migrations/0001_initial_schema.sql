-- ============================================================================
-- Migration: 0001_initial_schema.sql
-- Bright Way School
--
-- RECONSTRUCTED from the schema and policy details verified in this project.
-- Use only on a NEW Supabase project, then run 0002_security_hardening.sql.
--
-- Create these public Storage buckets separately in the Supabase Dashboard:
--   school-assets
--   gallery
--
-- Do not run this on the existing development project: its tables already exist.
-- Review against the current application models before production use.
-- ============================================================================

BEGIN;

-- 1. Tables

CREATE TABLE public.admin_profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name text NOT NULL,
    role text NOT NULL DEFAULT 'admin'
        CONSTRAINT admin_profiles_role_check
        CHECK (role IN ('admin', 'editor')),
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.page_contents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_slug text NOT NULL UNIQUE,
    content jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_published boolean NOT NULL DEFAULT true,
    updated_at timestamptz DEFAULT now(),
    updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE public.facilities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text,
    image_url text,
    display_order integer NOT NULL DEFAULT 0,
    is_published boolean NOT NULL DEFAULT false,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.gallery_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text,
    description text,
    image_url text NOT NULL,
    category text NOT NULL,
    display_order integer NOT NULL DEFAULT 0,
    is_published boolean NOT NULL DEFAULT false,
    created_at timestamptz DEFAULT now()
);

CREATE TABLE public.announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text,
    category text,
    image_url text,
    published_at timestamptz,
    is_published boolean NOT NULL DEFAULT false,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.site_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key text NOT NULL UNIQUE,
    setting_value jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_public boolean NOT NULL DEFAULT true,
    updated_at timestamptz DEFAULT now()
);

-- 2. Indexes

CREATE INDEX facilities_display_order_idx
    ON public.facilities (display_order);

CREATE INDEX gallery_images_category_display_order_idx
    ON public.gallery_images (category, display_order);

CREATE INDEX announcements_published_idx
    ON public.announcements (is_published, published_at DESC);

-- Unique constraints on page_slug and setting_key create their own indexes.

-- 3. Initial helper function.
-- Migration 0002 replaces this with separate admin/editor authorization.

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
    SELECT EXISTS (
        SELECT 1
        FROM public.admin_profiles
        WHERE id = (SELECT auth.uid())
          AND role IN ('admin', 'editor')
    );
$function$;

-- 4. Enable RLS

ALTER TABLE public.admin_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_contents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.facilities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

-- 5. Initial policies.
-- The recursive admin_profiles management policy is removed by migration 0002.
-- Do not use this initial state as a finished production security configuration.

CREATE POLICY "Admins can view own profile"
ON public.admin_profiles
FOR SELECT
TO authenticated
USING (
    id = (SELECT auth.uid())
    OR (SELECT public.is_admin())
);

CREATE POLICY "Admins can manage profiles"
ON public.admin_profiles
FOR ALL
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.admin_profiles p
        WHERE p.id = (SELECT auth.uid())
          AND p.role = 'admin'
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.admin_profiles p
        WHERE p.id = (SELECT auth.uid())
          AND p.role = 'admin'
    )
);

CREATE POLICY "Public can view published pages"
ON public.page_contents
FOR SELECT
TO anon, authenticated
USING (is_published = true);

CREATE POLICY "Admins can manage page contents"
ON public.page_contents
FOR ALL
TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Public can view published facilities"
ON public.facilities
FOR SELECT
TO anon, authenticated
USING (is_published = true);

CREATE POLICY "Admins can manage facilities"
ON public.facilities
FOR ALL
TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Public can view published gallery"
ON public.gallery_images
FOR SELECT
TO anon, authenticated
USING (is_published = true);

CREATE POLICY "Admins can manage gallery"
ON public.gallery_images
FOR ALL
TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Public can view published announcements"
ON public.announcements
FOR SELECT
TO anon, authenticated
USING (is_published = true AND published_at <= now());

CREATE POLICY "Admins can manage announcements"
ON public.announcements
FOR ALL
TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY "Public can view public settings"
ON public.site_settings
FOR SELECT
TO anon, authenticated
USING (is_public = true);

CREATE POLICY "Admins can manage settings"
ON public.site_settings
FOR ALL
TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

-- 6. Initial Storage policies.
-- Create the two public buckets in the Dashboard before using Storage.
-- Migration 0002 replaces these bucket-specific write policies.

CREATE POLICY "Public can view school assets"
ON storage.objects
FOR SELECT
TO anon, authenticated
USING (bucket_id IN ('school-assets', 'gallery'));

CREATE POLICY "Admins can upload school images"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id IN ('school-assets', 'gallery')
    AND (SELECT public.is_admin())
);

CREATE POLICY "Admins can update school images"
ON storage.objects
FOR UPDATE
TO authenticated
USING (
    bucket_id IN ('school-assets', 'gallery')
    AND (SELECT public.is_admin())
)
WITH CHECK (
    bucket_id IN ('school-assets', 'gallery')
    AND (SELECT public.is_admin())
);

CREATE POLICY "Admins can delete school images"
ON storage.objects
FOR DELETE
TO authenticated
USING (
    bucket_id IN ('school-assets', 'gallery')
    AND (SELECT public.is_admin())
);

COMMIT;

