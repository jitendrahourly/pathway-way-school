BEGIN;

-- Messages submitted from the public Contact Us form.
CREATE TABLE public.contact_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  phone text,
  subject text,
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_contact_messages_created_at
  ON public.contact_messages (created_at DESC);

GRANT USAGE, SELECT ON SEQUENCE public.contact_messages_id_seq TO anon, authenticated;
GRANT INSERT ON public.contact_messages TO anon, authenticated;
GRANT SELECT, UPDATE, DELETE ON public.contact_messages TO authenticated;

ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

-- Visitors may submit a message, but nobody can read submissions publicly.
CREATE POLICY "contact_messages_public_insert"
  ON public.contact_messages
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    char_length(name) BETWEEN 1 AND 120
    AND char_length(email) BETWEEN 3 AND 160
    AND char_length(message) BETWEEN 1 AND 2000
    AND (phone IS NULL OR char_length(phone) <= 40)
    AND (subject IS NULL OR char_length(subject) <= 160)
  );

-- Only administrators can read and manage submitted messages.
CREATE POLICY "contact_messages_admin_select"
  ON public.contact_messages
  FOR SELECT
  TO authenticated
  USING (public.is_admin());

CREATE POLICY "contact_messages_admin_update"
  ON public.contact_messages
  FOR UPDATE
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY "contact_messages_admin_delete"
  ON public.contact_messages
  FOR DELETE
  TO authenticated
  USING (public.is_admin());

COMMIT;
