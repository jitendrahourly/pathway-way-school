BEGIN;

-- Tables (unchanged definitions)
CREATE TABLE public.admin_profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  role text NOT NULL DEFAULT 'admin' CHECK (role = 'admin'),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.page_contents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_slug text NOT NULL UNIQUE,
  content jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_published boolean DEFAULT true,
  updated_at timestamptz DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE public.announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL,
  category text NOT NULL,
  image_url text,
  published_at timestamptz,
  is_published boolean DEFAULT false,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.facilities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  image_url text,
  display_order integer DEFAULT 0,
  is_published boolean DEFAULT false,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.gallery_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  image_url text NOT NULL,
  category text NOT NULL,
  display_order integer DEFAULT 0,
  is_published boolean DEFAULT false,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE public.site_settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key text NOT NULL UNIQUE,
  setting_value jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_public boolean DEFAULT true,
  updated_at timestamptz DEFAULT now()
);

-- Schema usage
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

-- Least-privilege table grants
-- anon: read-only public content
GRANT SELECT ON public.page_contents, public.announcements, public.facilities, public.gallery_images, public.site_settings TO anon;

-- authenticated: read all; write content where RLS allows; no insert into admin_profiles (RLS always denies)
GRANT SELECT, UPDATE, DELETE ON public.admin_profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.page_contents, public.announcements, public.facilities, public.gallery_images, public.site_settings TO authenticated;

-- service_role: full
GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;

-- Sequences
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- Indexes
CREATE INDEX idx_announcements_published ON public.announcements(is_published, published_at DESC);
CREATE INDEX idx_facilities_order ON public.facilities(display_order);
CREATE INDEX idx_gallery_category ON public.gallery_images(category);
CREATE INDEX idx_gallery_order ON public.gallery_images(display_order);

-- Functions
CREATE OR REPLACE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path='' AS $$
  SELECT EXISTS (SELECT 1 FROM public.admin_profiles WHERE id = auth.uid() AND role = 'admin');
$$;
CREATE OR REPLACE FUNCTION public.is_editor() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path='' AS $$
  SELECT false;
$$;
CREATE OR REPLACE FUNCTION public.is_editor_or_admin() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path='' AS $$
  SELECT public.is_admin();
$$;
CREATE OR REPLACE FUNCTION public.has_role(required_role text) RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path='' AS $$
  SELECT EXISTS (SELECT 1 FROM public.admin_profiles WHERE id = auth.uid() AND role = required_role);
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.is_editor() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.is_editor_or_admin() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.has_role(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.is_editor() TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.is_editor_or_admin() TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.has_role(text) TO anon, authenticated;
GRANT ALL ON FUNCTION public.is_admin(), public.is_editor(), public.is_editor_or_admin(), public.has_role(text) TO service_role;

-- RLS
ALTER TABLE public.admin_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_contents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.facilities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

-- Clean policies (legacy duplicates intentionally omitted)
CREATE POLICY "admin_profiles_select" ON public.admin_profiles FOR SELECT USING (id = auth.uid() OR public.is_admin());
CREATE POLICY "admin_profiles_insert_deny" ON public.admin_profiles FOR INSERT WITH CHECK (false);
CREATE POLICY "admin_profiles_update" ON public.admin_profiles FOR UPDATE USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "admin_profiles_delete" ON public.admin_profiles FOR DELETE USING (public.is_admin());

CREATE POLICY "page_contents_public_select" ON public.page_contents FOR SELECT USING (is_published = true);
CREATE POLICY "page_contents_staff_select" ON public.page_contents FOR SELECT USING (public.is_editor_or_admin());
CREATE POLICY "page_contents_write" ON public.page_contents FOR ALL USING (public.is_editor_or_admin()) WITH CHECK (public.is_editor_or_admin());

CREATE POLICY "announcements_public_select" ON public.announcements FOR SELECT USING (is_published = true AND published_at <= now());
CREATE POLICY "announcements_staff_select" ON public.announcements FOR SELECT USING (public.is_editor_or_admin());
CREATE POLICY "announcements_write" ON public.announcements FOR ALL USING (public.is_editor_or_admin()) WITH CHECK (public.is_editor_or_admin());

CREATE POLICY "facilities_public_select" ON public.facilities FOR SELECT USING (is_published = true);
CREATE POLICY "facilities_staff_select" ON public.facilities FOR SELECT USING (public.is_editor_or_admin());
CREATE POLICY "facilities_write" ON public.facilities FOR ALL USING (public.is_editor_or_admin()) WITH CHECK (public.is_editor_or_admin());

CREATE POLICY "gallery_images_public_select" ON public.gallery_images FOR SELECT USING (is_published = true);
CREATE POLICY "gallery_images_staff_select" ON public.gallery_images FOR SELECT USING (public.is_editor_or_admin());
CREATE POLICY "gallery_images_write" ON public.gallery_images FOR ALL USING (public.is_editor_or_admin()) WITH CHECK (public.is_editor_or_admin());

CREATE POLICY "site_settings_public_select" ON public.site_settings FOR SELECT USING (is_public = true);
CREATE POLICY "site_settings_write" ON public.site_settings FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

-- Storage
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES
  ('gallery', 'gallery', true, 5242880, ARRAY['image/jpeg','image/png','image/webp','image/svg+xml']),
  ('school-assets', 'school-assets', true, 5242880, ARRAY['image/jpeg','image/png','image/webp','image/svg+xml'])
ON CONFLICT (id) DO NOTHING;

GRANT SELECT ON storage.buckets, storage.objects TO anon;
GRANT SELECT ON storage.buckets TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON storage.objects TO authenticated;
GRANT ALL ON storage.buckets, storage.objects TO service_role;

CREATE POLICY "storage_public_read" ON storage.objects FOR SELECT USING (bucket_id IN ('gallery','school-assets'));
CREATE POLICY "storage_admin_insert" ON storage.objects FOR INSERT WITH CHECK (bucket_id IN ('gallery','school-assets') AND public.is_admin());
CREATE POLICY "storage_admin_update" ON storage.objects FOR UPDATE USING (bucket_id IN ('gallery','school-assets') AND public.is_admin()) WITH CHECK (bucket_id IN ('gallery','school-assets') AND public.is_admin());
CREATE POLICY "storage_admin_delete" ON storage.objects FOR DELETE USING (bucket_id IN ('gallery','school-assets') AND public.is_admin());

COMMIT;
